def b_label(b):
    """b の文字列表記を既存ファイル名と一致させる（0 → '0', 1 → '1.0', 0.2 → '0.2'）"""
    b = float(b)
    return "0" if b == 0 else str(b)


def pattern_scale(pattern):
    """更新値の最大絶対値が 2 以下なら 1/5 スケールと判定する"""
    vals = [abs(float(x)) for x in re.findall(r'[+-]?\d+(?:\.\d+)?', pattern)]
    return "1/5" if max(vals) <= 2.0 else "normal"


# ------------------------------------------------------------
# 3. variant（対照実験・長時間実行）を表すフォルダ名サフィックス
#    既定条件（10000MCS, リセットなし, 旧打ち切り, 評判丸めなし）は "" で、
#    既存フォルダ "Z_b_change報酬罰" をそのまま使う。
# ------------------------------------------------------------
def make_variant(steps=10000, reset_rep="none", stop="legacy", rep_fix=False):
    v = ""
    if steps != 10000:
        v += f"_T{steps}"
    if reset_rep != "none":
        v += f"_reset-{reset_rep}"
    if stop != "legacy":
        v += f"_stop-{stop}"
    if rep_fix:
        v += "_repfix"
    return v


def root_dir(date_dir, pattern, variant=""):
    """データの保存ルート（run_simulation.py からの相対パス）"""
    return f"../../{date_dir}/Z_b_change報酬罰{variant}/{pattern}"


def seed_suffix(seed):
    """seed 未指定（従来の非固定乱数）なら従来ファイル名のまま"""
    return "" if seed is None else f"_seed={seed}"


def log_zip_path(date_dir, model, pattern, Z, omega, seed, variant=""):
    """詳細ログ L1〜L8 の zip（1タスク = 1zip, 中に b ごとのフォルダ）"""
    s = "none" if seed is None else seed
    return f"{root_dir(date_dir, pattern, variant)}/Logs/{model}_Z={Z}_omega={omega}_seed={s}.zip"


